// Build sequentially numbered exhibits (#01 .. #NN) linked to real SpatialItems!
function buildCatalog(): { groups: MuseumGroup[]; exhibits: MuseumExhibit[] } {
  const bySection = {
    experience: getItemsForSection("experience"),
    projects: getItemsForSection("projects"),
    about: getItemsForSection("about"),
  };

  let num = 1;
  const allExhibits: MuseumExhibit[] = [];
  const groups: MuseumGroup[] = [];

  for (const raw of RAW_GROUPS) {
    const list = bySection[raw.itemSection];
    const matched = list.find((it) => it.slug === raw.itemSlug) ?? list[0];
    const pal = matched.palette;
    const groupExhibits: MuseumExhibit[] = [];

    for (const v of raw.variants) {
      const ex: MuseumExhibit = {
        number: num,
        code: `#${String(num).padStart(2, "0")}`,
        id: v.id,
        groupId: raw.id,
        groupTitle: raw.title,
        sectionLabel: raw.sectionLabel,
        name: v.name,
        era: v.era,
        isActive: Boolean(v.isActive),
        isUserFavorite: Boolean(v.isUserFavorite),
        isAiFavorite: Boolean(v.isAiFavorite),
        blindGuess: v.blindGuess,
        councilScore: v.councilScore,
        notes: v.notes,
        palette: pal,
        formation: raw.formation,
        variantKey: v.variantKey,
        useLegacyFormation: Boolean(v.useLegacyFormation),
      };
      num++;
      groupExhibits.push(ex);
      allExhibits.push(ex);
    }

    groups.push({
      id: raw.id,
      title: raw.title,
      subtitle: raw.subtitle,
      sectionLabel: raw.sectionLabel,
      formation: raw.formation,
      palette: pal,
      exhibits: groupExhibits,
    });
  }

  return { groups, exhibits: allExhibits };
}

const built = buildCatalog();
export const MUSEUM_GROUPS: MuseumGroup[] = built.groups;
export const ALL_EXHIBITS: MuseumExhibit[] = built.exhibits;

export function getExhibitByNumber(n: number): MuseumExhibit | undefined {
  return ALL_EXHIBITS.find((e) => e.number === n);
}

export function getExhibitById(id: string): MuseumExhibit | undefined {
  return ALL_EXHIBITS.find((e) => e.id === id);
}

/**
 * Evaluate the 120-cube Large Hero pose for any MuseumExhibit.
 */
export function evaluateExhibitHero(
  exhibit: MuseumExhibit,
  idx: number,
  t: number,
  centerX: number,
  centerY: number,
): CubeTarget {
  if (exhibit.variantKey) {
    const ev = ALL_VARIANT_EVALUATORS[exhibit.variantKey];
    if (ev) {
      const res = ev.hero(idx, CUBE_COUNT, t, exhibit.palette);
      const floatY = Math.sin(t * 0.8 + (idx / CUBE_COUNT) * 2) * 0.035;
      return {
        ...res,
        x: centerX + res.x,
        y: centerY + res.y + floatY,
        z: res.z + 0.55,
      };
    }
  }
  const fakeItem: SpatialItem = {
    uid: `museum:${exhibit.id}`,
    slug: exhibit.id,
    section: "projects",
    title: exhibit.groupTitle,
    shortLabel: exhibit.groupTitle,
    subtitle: "",
    eyebrow: "",
    formation: exhibit.formation,
    palette: exhibit.palette,
    payload: {
      kind: "about",
      about: {
        kind: "contact",
        eyebrow: "",
        headline: "",
        body: "",
        email: "",
        links: [],
      },
    },
  };
  return computeHeroFormation(
    fakeItem,
    idx,
    CUBE_COUNT,
    t,
    centerX,
    centerY,
    Boolean(exhibit.useLegacyFormation),
  );
}

/**
 * Evaluate the 12-cube Small Overview Mini pose for any MuseumExhibit.
 */
export function evaluateExhibitMini(
  exhibit: MuseumExhibit,
  localIdx: number,
  localCount: number,
  t: number,
  boost = 1.65,
): MiniResult {
  if (exhibit.variantKey) {
    const ev = ALL_VARIANT_EVALUATORS[exhibit.variantKey];
    if (ev) {
      const sc = 0.172 * boost;
      return ev.mini(localIdx, localCount, t, boost, sc, exhibit.palette);
    }
  }
  const base = computeMiniFormation(
    exhibit.formation,
    false,
    localIdx,
    localCount,
    t,
    false,
    exhibit.palette,
    Boolean(exhibit.useLegacyFormation),
  );
  const k = boost;
  return {
    ...base,
    dx: base.dx * k,
    dy: base.dy * k,
    dz: base.dz * k,
    scale: base.scale * k,
  };
}
